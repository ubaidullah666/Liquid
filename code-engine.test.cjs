const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const { HistoryStore, contextFor } = require('./history-store.cjs');

test('coding IPC streams Qwen output, saves selected files, and rejects invalid requests', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'liquid-code-'));
  const attachmentFile=path.join(directory,'readme.txt');fs.writeFileSync(attachmentFile,'Attached source information');
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  let handler, request, copied, locked = false, canceled = false, fetchMode = 'success';
  const events = [];
  const window = new EventEmitter();
  window.isDestroyed = () => false;
  window.webContents = { mainFrame: {}, isDestroyed: () => false, send: (_channel, data) => events.push(data) };
  const electron = {
    ipcMain: { handle: (_name, fn) => { handler = fn; }, removeHandler: () => {} },
    clipboard: { writeText: text => { copied = text; } },
    dialog: { showSaveDialog: async () => ({ canceled, filePath: path.join(directory, 'output.py') }),showOpenDialog:async(_window,options)=>({canceled:false,filePaths:options.properties.includes('openFile')?[attachmentFile]:[directory]}) }
  };
  const module = { exports: {} };
  const environment = {
    module,
    require: name => name === 'electron' ? electron : name === './history-store.cjs' ? { HistoryStore, contextFor } : name === './code-runner.cjs' ? {createCodeRunner:()=>({run:async()=>({output:'43\n',exitCode:0,status:'complete',error:''}),stop(){}})} : require(name),
    fetch: async (_url, options) => {
      if (_url.endsWith('/api/tags')) return {ok:true,json:async()=>({models:[{name:'qwen2.5:3b'},{name:'qwen3-coder:30b'},{name:'minimax-m3:cloud',remote_model:'minimax-m3'}]})};
      if (_url.endsWith('/api/show'))return {ok:true,json:async()=>({capabilities:['completion','tools'],thinking:{values:[false,true]}})};
      if (fetchMode === 'offline') throw Error('fetch failed');
      if (fetchMode === 'cloud-denied') return {ok:false,status:401,text:async()=> 'unauthorized'};
      if (fetchMode === 'wait') return new Promise((_resolve, reject) => options.signal.addEventListener('abort', () => reject(Error('Aborted')), { once: true }));
      request = JSON.parse(options.body);
      return { ok: true, body: (async function* () { yield Buffer.from('{"message":{"content":"print(42)"},"done":true}\n'); })() };
    }, AbortController, AbortSignal, TextDecoder, setTimeout, clearTimeout, console
  };
  new Function(...Object.keys(environment), fs.readFileSync(path.join(__dirname, 'chat-engine.cjs'), 'utf8'))(...Object.values(environment));
  const chat = module.exports.createChat(window, directory, { requireOpen() { if (locked) throw Error('Unlock your profile first.'); }, context(){return {role:'system',content:'Calendar context'};} });
  const sender = { sender: window.webContents, senderFrame: window.webContents.mainFrame };
  const call = (command, payload) => handler(sender, command, payload);
  assert.equal((await call('mode')).mode,'chat');
  assert.equal((await call('generate-code',{prompt:'Write code'})).ok,false);
  assert.equal((await call('choose-workspace')).ok,false);
  assert.equal((await call('set-mode','codex')).ok,true);
  const result = await call('generate-code', { prompt: 'Print 42', language: 'Python', source: 'print(1)' });
  assert.equal(result.ok, true);
  for (let i = 0; chat.busy && i < 100; i++) await new Promise(resolve => setTimeout(resolve, 5));
  assert.equal(chat.busy, false);
  assert.equal(request.model, 'qwen2.5:3b');
  assert.match(request.messages[0].content, /Return only source code/);
  assert.match(request.messages[1].content, /print\(1\)/);
  assert.equal(chat.history.all().at(-1).kind, 'code');
  assert.equal(chat.history.all().at(-1).content, 'print(42)');
  assert.ok(events.some(event => event.type === 'delta' && event.text === 'print(42)'));
  const answer = chat.history.all().at(-1);
  assert.equal((await call('run-code', {id: answer.id, index: 0, content:'print(43)'})).ok, true);
  assert.equal(chat.history.all().at(-1).codeRuns[0].output, '43\n');
  assert.equal(chat.history.all().at(-1).codeRuns[0].source, 'print(43)');
  assert.match(contextFor(chat.history.all(), 'explain output').at(-1).content, /Actual local code run results/);
  assert.equal((await call('run-code', {id: answer.id, index: 9})).ok, false);
  assert.equal((await call('choose-workspace')).ok,true);
  assert.equal((await call('create-file',{id:answer.id,index:0,filename:'src/hello.py'})).ok,true);
  assert.equal(fs.readFileSync(path.join(directory,'src','hello.py'),'utf8'),'print(42)');
  assert.equal((await call('create-file',{id:answer.id,index:0,filename:'../outside.py'})).ok,false);
  assert.equal((await call('create-file',{id:answer.id,index:0,filename:'src/hello.py',content:'changed'})).ok,false);
  assert.equal(fs.readFileSync(path.join(directory,'src','hello.py'),'utf8'),'print(42)');
  const codexSession=(await call('current')).sessionId;
  await call('set-mode','chat');
  assert.equal((await call('run-code',{id:answer.id,index:0})).ok,false);
  assert.equal((await call('save-code',{content:'x'})).ok,false);
  assert.equal((await call('current')).records.length,0);
  assert.equal((await call('attach-files')).attachments[0].name,'readme.txt');
  assert.equal((await call('features')).attachments.length,1);
  await call('send','Explain the weather');
  for(let i=0;chat.busy&&i<100;i++)await new Promise(resolve=>setTimeout(resolve,5));
  assert.match(request.messages[0].content,/You are in Chat mode/);
  assert.ok(request.messages.some(message=>message.content.includes('Attached source information')));
  assert.equal((await call('features')).attachments.length,0);
  assert.equal(request.messages.some(message=>message.content.includes('print(42)')),false);
  await call('set-mode','codex');
  assert.equal((await call('current')).sessionId,codexSession);
  assert.equal((await call('set-options',{deep:true})).ok,true);
  assert.equal((await call('select-model','qwen3-coder:30b')).ok,true);
  await call('send','Write JavaScript');
  for(let i=0;chat.busy&&i<100;i++)await new Promise(resolve=>setTimeout(resolve,5));
  assert.equal(request.model,'qwen3-coder:30b');
  assert.equal(chat.history.all().at(-1).model,'qwen3-coder:30b');
  assert.match(request.messages[0].content,/qwen3-coder:30b/);
  assert.equal((await call('set-options',{deep:true})).ok,true);
  assert.equal((await call('select-model','minimax-m3:cloud')).ok,true);
  await call('generate-code',{prompt:'Write Python',language:'Python'});
  for(let i=0;chat.busy&&i<100;i++)await new Promise(resolve=>setTimeout(resolve,5));
  assert.equal(request.model,'minimax-m3:cloud');
  assert.equal(chat.history.all().at(-1).cloud,true);
  fetchMode='cloud-denied';
  await call('send','Hello');
  for(let i=0;chat.busy&&i<100;i++)await new Promise(resolve=>setTimeout(resolve,5));
  assert.match(chat.history.all().at(-1).error,/ollama signin/);
  fetchMode='success';
  assert.equal((await call('copy-code', { content: 'print(42)' })).ok, true);
  assert.equal(copied, 'print(42)');
  assert.equal((await call('save-code', { content: 'print(42)', filename: 'code.py' })).ok, true);
  assert.equal((await call('download-code',{content:'print(42)',filename:'code.py'})).ok,true);
  assert.equal(fs.readFileSync(path.join(directory, 'output.py'), 'utf8'), 'print(42)');
  canceled = true;
  assert.equal((await call('save-code', { content: 'print(0)' })).canceled, true);
  assert.equal(fs.readFileSync(path.join(directory, 'output.py'), 'utf8'), 'print(42)');
  assert.equal((await call('generate-code', { prompt: 'Revise', source: 'x'.repeat(24001) })).ok, false);
  assert.equal((await call('save-code', { content: '' })).ok, false);
  fetchMode = 'wait';
  await call('generate-code', { prompt: 'Write code' });
  assert.equal((await call('set-mode','chat')).ok,false);
  assert.equal((await call('select-model','qwen2.5:3b')).ok,false);
  assert.equal((await call('generate-code', { prompt: 'Another request' })).ok, false);
  await call('stop');
  for (let i = 0; chat.busy && i < 100; i++) await new Promise(resolve => setTimeout(resolve, 5));
  assert.equal(chat.history.all().at(-1).status, 'stopped');
  fetchMode = 'offline';
  await call('generate-code', { prompt: 'Write code' });
  for (let i = 0; chat.busy && i < 100; i++) await new Promise(resolve => setTimeout(resolve, 5));
  assert.equal(chat.history.all().at(-1).status, 'error');
  assert.match(chat.history.all().at(-1).error, /Cannot reach Ollama/);
  locked = true;
  assert.equal((await call('generate-code', { prompt: 'Print 1' })).ok, false);
  assert.equal((await call('copy-code', { content: 'secret' })).ok, false);
  assert.equal(copied, 'print(42)');
  await assert.rejects(handler({ sender: {} }, 'copy-code', { content: 'x' }), /Untrusted/);
  window.emit('closed');
});
